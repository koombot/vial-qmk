static void render_status(void) {
    // Layer
    oled_write_ln_P(PSTR("Lyr:"), false);
    switch (get_highest_layer(layer_state)) {
        case _QWERTY: oled_write_ln_P(PSTR("BASE"),  false); break;
        case _LOWER:  oled_write_ln_P(PSTR("LOWER"), false); break;
        case _RAISE:  oled_write_ln_P(PSTR("RAISE"), false); break;
        case _ADJUST: oled_write_ln_P(PSTR("ADJST"), false); break;
        case _NUMPAD: oled_write_ln_P(PSTR("NUMPD"), false); break;
        default:      oled_write_ln_P(PSTR("????"),  false); break;
    }
    oled_write_ln_P(PSTR(""), false);

    // Modifier keys — always visible, inverted (highlighted) when held
    uint8_t mods = get_mods() | get_oneshot_mods();
    oled_write_ln_P(PSTR("Mods:"), false);
    oled_write_P(PSTR("SFT "), (bool)(mods & MOD_MASK_SHIFT));
    oled_write_ln_P(PSTR("CTL"),  (bool)(mods & MOD_MASK_CTRL));
    oled_write_P(PSTR("ALT "), (bool)(mods & MOD_MASK_ALT));
    oled_write_ln_P(PSTR("GUI"),  (bool)(mods & MOD_MASK_GUI));
    oled_write_ln_P(PSTR(""), false);

    // Lock states
    oled_write_ln_P(PSTR("Lock:"), false);
    led_t led_state = host_keyboard_led_state();
    oled_write_P(PSTR("CAP "), led_state.caps_lock);
    oled_write_ln_P(PSTR("CpWd"), is_caps_word_on());

    // OS logo (64x56px, 7 lines × 64 columns = 448 bytes)
    oled_set_cursor(0, 9);
    oled_write_raw_P(keymap_config.swap_lctl_lgui ? os_logo_mac : os_logo_win, 448);
}

