static bool oled_transitioned = false;

bool oled_task_user(void) {
    // Show the Sofle logo on boot for BOOT_LOGO_MS milliseconds
    if (timer_read32() < BOOT_LOGO_MS) {
        oled_transitioned = false;
        return true; // hand control back so oled_task_kb renders the logo
    }

    // Clear stale logo pixels exactly once when switching to content
    if (!oled_transitioned) {
        oled_clear();
        oled_transitioned = true;
    }

    if (is_keyboard_master()) {
        render_status();
    } else {
        static bool right_oled_sleeping = false;
        if (last_input_activity_elapsed() > RIGHT_OLED_TIMEOUT) {
            if (!right_oled_sleeping) {
                oled_off();
                right_oled_sleeping = true;
            }
            return false;
        }
        if (right_oled_sleeping) {
            oled_on();
            right_oled_sleeping = false;
        }
        render_bongo_cat();
    }
    return false;
}

